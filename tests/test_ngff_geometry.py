def test_missing_translations_are_not_silently_replaced_by_block_mean_assumptions(real_ome_zarr, mock_nd_metadata):
    root = zarr.open_group(real_ome_zarr, mode="a")
    images = root.attrs["multiscales"]
    for dataset in images[0]["datasets"]:
        dataset["coordinateTransformations"] = dataset["coordinateTransformations"][:1]
    root.attrs["multiscales"] = images
    stub, _ = zarr_mod.zarr_to_sitk_stub(real_ome_zarr, mock_nd_metadata, level=3)
    assert stub.GetOrigin() == (0, 0, 0)


@pytest.mark.parametrize("backend", ["stub", "sitk", "ants"])
def test_dataset_then_global_transforms_control_spacing_and_origin(real_ome_zarr, mock_nd_metadata, backend):
    root = zarr.open_group(real_ome_zarr, mode="a")
    images = root.attrs["multiscales"]
    image = images[0]
    image["datasets"][0]["coordinateTransformations"][1]["translation"] = [0, 0, 1, 2, 3]
    image["datasets"][2]["coordinateTransformations"][1]["translation"] = [0, 0, 6, 10, 15]
    image["coordinateTransformations"] = [
        {"type": "scale", "scale": [1, 1, 2, 3, 4]},
        {"type": "translation", "translation": [0, 0, 7, 11, 13]},
    ]
    root.attrs["multiscales"] = images
    if backend == "stub":
        image, _ = zarr_mod.zarr_to_sitk_stub(real_ome_zarr, mock_nd_metadata, level=2)
    elif backend == "sitk":
        image = zarr_mod.zarr_to_sitk(real_ome_zarr, mock_nd_metadata, level=2)
    else:
        image = zarr_mod.zarr_to_ants(real_ome_zarr, mock_nd_metadata, level=2)
    origin = image.origin if backend == "ants" else image.GetOrigin()
    spacing = image.spacing if backend == "ants" else image.GetSpacing()
    assert origin == pytest.approx((-73, -41, 19))
    assert spacing == pytest.approx((8, 12, 16) if backend == "ants" else (16, 12, 8))
    anchored, _ = zarr_mod.zarr_to_sitk_stub(real_ome_zarr, mock_nd_metadata, level=2, set_origin=(1, 2, 3))
    assert anchored.GetOrigin() == pytest.approx((-47, -22, 13))


def test_pyramid_translation_interpretation_changes_physical_geometry_without_mutating_sources(faulty_asset):
    asset, subject = faulty_asset
    raw_file = Path(asset.alignment_zarr_uri) / ".zattrs"
    original_bytes = raw_file.read_bytes()
    original_attributes = asset.zarr_attributes.raw
    original_processing = copy.deepcopy(dict(asset.processing))
    uncorrected, _ = asset.stub(level=3)
    expected_raw = (0, 0, 0) if subject == "771432" else (-0.0035, -0.0035, 0.0035)
    assert uncorrected.GetOrigin() == pytest.approx(expected_raw)
    corrected = asset.with_pyramid_translation_correction(**EVIDENCE)
    assert corrected.geometry.evaluations[0].outcome == Applicability.APPLICABLE
    assert corrected.geometry.evaluations[0].rule_id == "smartspim.pyramid-translations"
    assert corrected.geometry.evaluations[0].rule_revision == "1"
    assert len(corrected.geometry.changes) == 3
    expected = (-0.0063, -0.0063, 0.007)
    assert corrected.stub(level=3)[0].GetOrigin() == pytest.approx(expected)
    assert corrected.image(level=3).GetOrigin() == pytest.approx(expected)
    assert corrected.image(level=3, library="ants").origin == pytest.approx(expected)
    assert corrected.stub(level=0)[0].GetOrigin() == (0, 0, 0)
    full_resolution, _ = corrected.stub(level=0)
    coarse, _ = corrected.stub(level=3)
    for index in ((0, 0, 0), (1, 1, 1)):
        source_center = tuple(8 * i + 3.5 for i in index)
        assert coarse.TransformIndexToPhysicalPoint(index) == pytest.approx(
            full_resolution.TransformContinuousIndexToPhysicalPoint(source_center)
        )
    assert asset.stub(level=3)[0].GetOrigin() == pytest.approx(expected_raw)
    assert asset.zarr_attributes.raw == original_attributes
    assert dict(asset.processing) == original_processing
    assert raw_file.read_bytes() == original_bytes
    np.testing.assert_array_equal(asset.opened_zarr[0].data[3].compute(), corrected.opened_zarr[0].data[3].compute())
    restored = replay(corrected.geometry.original, corrected.geometry.manifest())
    assert restored.derived.raw == corrected.geometry.derived.raw


